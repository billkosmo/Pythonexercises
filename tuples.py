# δομή δεδομένων που μοιάζει με λίστα (list), αλλά είναι αμετάβλητη (immutable). Δηλαδή, αφού οριστεί, δεν μπορείς να αλλάξεις, να προσθέσεις ή να αφαιρέσεις στοιχεία από μέσα του.
# Χρησιμοποιείται όταν θέλουμε τα δεδομένα να είναι προστατευμένα από τυχαίες αλλαγές ή για μεγαλύτερη ταχύτητα και εξοικονόμηση μνήμης.

student = ("bill",18,"male") # με παρενθεσεις γινονται τα tuples

# συναρτησεις των tuples

print(student.count("bill")) # μετραει ποσες φορες υπαρχει αυτο μεσα στην παρενθεση στο tuple
print(student.index(18)) # βρισκει και εμφανιζει την θεση οπου βρισκεται το στοιχειο

for m in student:
    print(m , end=" ")

    print() # aαυτο αναγκαζει τον κερσορα να παει απο κατω

if "bill" in student:
    print("He is here!")