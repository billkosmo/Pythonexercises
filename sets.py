# SETS 
# Στην Python, ένα set (σύνολο) είναι μια ενσωματωμένη δομή δεδομένων (built-in data type) που χρησιμοποιείται για την αποθήκευση πολλαπλών στοιχείων σε μία μόνο
# Μοναδικότητα (Unique elements): Περιέχουν μόνο μοναδικά στοιχεία. Εάν προσθέσεις ένα στοιχείο που υπάρχει ήδη, το set το αγνοεί αυτόματα (χρησιμοποιείται συχνά για αφαίρεση διπλότυπων).
# Χωρίς σειρά (Unordered): Τα στοιχεία δεν έχουν κάποια σταθερή σειρά ή θέση. Δεν μπορείς να τα προσπελάσεις με δείκτες (indexes) όπως στις λίστες (π.χ. my_set[0] δεν λειτουργεί).
# Τροποποιήσιμα (Mutable): Μπορείς να προσθέσεις ή να αφαιρέσεις στοιχεία, αλλά τα ίδια τα στοιχεία που περιέχει πρέπει να είναι immutable (δηλαδή να μπορούν να γίνουν "hashable", π.χ. αριθμοί, strings, tuples - όχι λίστες)
# Γρήγορες αναζητήσεις: Είναι υλοποιημένα εσωτερικά ως hash tables, οπότε οι έλεγχοι ύπαρξης (π.χ. x in my_set) γίνονται εξαιρετικά γρήγορα

